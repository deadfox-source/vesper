    public static func getAscii(forCard cardName: String, element: ElementType) -> String {
        let normalized = cardName.uppercased().trimmingCharacters(in: .whitespacesAndNewlines)
        if let ascii = cards[normalized] {
            return ascii
        }
        
        switch element {
        case .fire:
            return cards["WANDS"] ?? cards["DEFAULT"]!
        case .water:
            return cards["CUPS"] ?? cards["DEFAULT"]!
        case .air:
            return cards["SWORDS"] ?? cards["DEFAULT"]!
        case .earth, .spirit:
            return cards["PENTACLES"] ?? cards["DEFAULT"]!
        }
    }

    public static func getArtOnly(forCard cardName: String, element: ElementType) -> String {
        let raw = getAscii(forCard: cardName, element: element)
        let lines = raw.components(separatedBy: .newlines)
        
        var cleanLines: [String] = []
        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.isEmpty { continue }
            cleanLines.append(line)
        }
        
        if cleanLines.isEmpty {
            return raw
        }
        return cleanLines.joined(separator: "\n")
    }
