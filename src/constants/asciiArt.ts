export const getAsciiForCard = (name: string, element: string): string => {
  if (ASCII_ART[name]) return ASCII_ART[name];
  
  switch(element) {
    case "FIRE": return ASCII_ART["WANDS"];
    case "WATER": return ASCII_ART["CUPS"];
    case "AIR": return ASCII_ART["SWORDS"];
    case "EARTH": return ASCII_ART["PENTACLES"];
    default: return ASCII_ART["DEFAULT"];
  }
};
